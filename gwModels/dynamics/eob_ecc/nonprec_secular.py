"""
Non-resummed 3PN evolution ODEs for aligned-spin eccentric binaries.
Numba JIT-compiled for performance.
"""

import math
from numba import njit
from ._common import (
    EULER_GAMMA, LOG2, LOG3, LOG5, PI,
    _zetadot_numba, integrate_dynamics,
)


@njit(cache=True, fastmath=True)
def _edot_numba(e, x, nu, chi_S, chi_A, delta, kappa_S, kappa_A):
    e2 = e * e
    e4 = e2 * e2
    e6 = e4 * e2
    e8 = e4 * e4
    e10 = e8 * e2
    e12 = e8 * e4
    e14 = e8 * e6
    e16 = e8 * e8
    e18 = e16 * e2
    nu2 = nu * nu
    nu3 = nu2 * nu
    oome2 = 1.0 - e2           # 1 - e^2
    sqrt_oome2 = math.sqrt(oome2)
    sqrt_x = math.sqrt(x)

    chiA2 = chi_A * chi_A
    chiS2 = chi_S * chi_S
    chiAS = chi_A * chi_S

    # Overall prefactor: -e*x^4*nu
    # The entire expression is: -(e*x^4*nu * (sum of terms))
    # We build "bracket" = sum of terms, then return -e*x^4*nu * bracket

    # ------------------------------------------------------------------
    # 0PN: (304 + 121*e^2) / (15*(1-e^2)^(5/2))
    # ------------------------------------------------------------------
    term_0pn = (304.0 + 121.0 * e2) / (15.0 * oome2**2.5)

    # ------------------------------------------------------------------
    # 1.5PN tail (non-spin):
    #   Sqrt[1-e^2]*(A + Sqrt[1-e^2]*B) * Pi*x^(3/2)
    #   / (1440*(1+Sqrt[1-e^2]))
    # where A = 170688 + 918000*e^2 + 2681305*e^4 - 6204647*e^6
    #       B = 207552 + 1366320*e^2 + 4743145*e^4
    # ------------------------------------------------------------------
    tail_A = 170688.0 + 918000.0 * e2 + 2681305.0 * e4 - 6204647.0 * e6
    tail_B = 207552.0 + 1366320.0 * e2 + 4743145.0 * e4
    tail_15pn = (sqrt_oome2 * (tail_A + sqrt_oome2 * tail_B)
                 * PI * x**1.5
                 / (1440.0 * (1.0 + sqrt_oome2)))

    # ------------------------------------------------------------------
    # 1PN (non-spin): -x * (...) / (2520*(1-e^2)^(7/2))
    # ------------------------------------------------------------------
    pn1_num = (e4 * (94887.0 + 19768.0 * nu)
               + 12.0 * e2 * (38698.0 + 21427.0 * nu)
               + 8.0 * (20547.0 + 24556.0 * nu))
    term_1pn = -x * pn1_num / (2520.0 * oome2**3.5)

    # ------------------------------------------------------------------
    # 2PN (non-spin): x^2 * (...) / (30240*(1-e^2)^(9/2))
    # Note: the Mathematica expression has a + sign for this term
    # ------------------------------------------------------------------
    pn2_num = (5040.0 * sqrt_oome2
               * (-304.0 + 183.0 * e2 + 121.0 * e4) * (-5.0 + 2.0 * nu)
               + 3.0 * e6 * (1056441.0 + 339608.0 * nu + 60256.0 * nu2)
               + 16.0 * (-765197.0 + 772695.0 * nu + 225792.0 * nu2)
               + 12.0 * e2 * (-949135.0 + 4137363.0 * nu + 987567.0 * nu2)
               + e4 * (22189718.0 + 27599862.0 * nu + 5073936.0 * nu2))
    term_2pn = x**2 * pn2_num / (30240.0 * oome2**4.5)

    # ------------------------------------------------------------------
    # 2.5PN tail (non-spin):
    #   Pi*x^(5/2) * (-2*A + Sqrt[1-e^2]*B)
    #   / (60480*Sqrt[1-e^2]*(1+Sqrt[1-e^2]))
    # where A = 192*(64857+131893*nu) + 15*e^2*(...) + ...
    #       B = -192*(134127+314102*nu) - 18*e^2*(...) + ...
    # ------------------------------------------------------------------
    tail25_A = (192.0 * (64857.0 + 131893.0 * nu)
                + 15.0 * e2 * (8027043.0 + 11184196.0 * nu)
                - 8.0 * e6 * (243994813.0 + 311245113.0 * nu)
                + e4 * (460715559.0 + 543565717.0 * nu)
                + e8 * (1409512490.0 + 1753308791.0 * nu))
    tail25_B = (-192.0 * (134127.0 + 314102.0 * nu)
                - 18.0 * e2 * (16084965.0 + 26975836.0 * nu)
                - e4 * (1325206659.0 + 1874351606.0 * nu)
                + e6 * (2273373309.0 + 2420224238.0 * nu))
    tail_25pn = (PI * x**2.5
                 * (-2.0 * tail25_A + sqrt_oome2 * tail25_B)
                 / (60480.0 * sqrt_oome2 * (1.0 + sqrt_oome2)))

    # ------------------------------------------------------------------
    # 1.5PN SO: x^(3/2) * (...) / (90*(1-e^2)^4)
    # ------------------------------------------------------------------
    so_15pn_num = ((-16232.0 - 248.0 * e2 + 1869.0 * e4) * delta * chi_A
                   + (-3.0 * e4 * (-623.0 + 92.0 * nu)
                      + 8.0 * (-2029.0 + 1664.0 * nu)
                      + 4.0 * e2 * (-62.0 + 1993.0 * nu)) * chi_S)
    so_15pn = x**1.5 * so_15pn_num / (90.0 * oome2**4)

    # ------------------------------------------------------------------
    # 2.5PN SO tail:
    #   -Pi*x^3 * (2*Sqrt[1-e^2]*(...) - (-1+e^2)*(...))
    #   / (2160*(1-e^2)^(3/2)*(1+Sqrt[1-e^2]))
    # ------------------------------------------------------------------
    # sqrt(1-e^2) block
    so_25pn_tail_sqrt_chiA = ((1125696.0 + 6578040.0 * e2
                               + 21702145.0 * e4 - 62873690.0 * e6
                               + 21294539.0 * e8) * delta * chi_A)
    so_25pn_tail_sqrt_chiS = ((e8 * (21294539.0 - 34444693.0 * nu)
                               + e4 * (21702145.0 - 19192049.0 * nu)
                               - 2496.0 * (-451.0 + 377.0 * nu)
                               - 168.0 * e2 * (-39155.0 + 35344.0 * nu)
                               + e6 * (-62873690.0 + 66602161.0 * nu))
                              * chi_S)
    sqrt_block_so25 = 2.0 * sqrt_oome2 * (so_25pn_tail_sqrt_chiA
                                           + so_25pn_tail_sqrt_chiS)
    # (-1+e^2) block  =>  -(1-e^2) block, so -(-1+e^2) = (1-e^2)
    # The expression has: - (-1+e^2)*(...)  = (1-e^2)*(...)
    # But we need to be careful: -(-1+e^2) = -(e^2-1) = (1-e^2)
    nso_25pn_tail_e2_chiA = (2.0 * (1235136.0 + 5955768.0 * e2
                                     + 13592197.0 * e4
                                     - 97575704.0 * e6
                                     + 82122675.0 * e8)
                             * delta * chi_A)
    nso_25pn_tail_e2_chiS = ((e8 * (164245350.0 - 72544789.0 * nu)
                              + e4 * (27184394.0 - 41431378.0 * nu)
                              - 384.0 * (-6433.0 + 4973.0 * nu)
                              - 144.0 * e2 * (-82719.0 + 86036.0 * nu)
                              + e6 * (-195151408.0 + 122944911.0 * nu))
                             * chi_S)
    # Full expression: 2*sqrt*(...) - (-1+e^2)*(...)
    # = 2*sqrt*(...) + (1-e^2)*(...)
    so_25pn_tail_num = (sqrt_block_so25
                        + oome2 * (nso_25pn_tail_e2_chiA
                                   + nso_25pn_tail_e2_chiS))
    so_25pn_tail = (-PI * x**3 * so_25pn_tail_num
                    / (2160.0 * oome2**1.5 * (1.0 + sqrt_oome2)))

    # ------------------------------------------------------------------
    # 2.5PN SO (non-tail): -x^(5/2) * (...) / (60480*(1-e^2)^5*(1+sqrt(1-e^2)))
    # ------------------------------------------------------------------
    # Main block (no sqrt(1-e^2))
    so_25pn_main_chiA = (delta * (20822976.0
                                  + e6 * (20081457.0 - 944748.0 * nu)
                                  - 69155072.0 * nu
                                  - 24.0 * e2 * (6113054.0 + 1199583.0 * nu)
                                  + 4.0 * e4 * (8638002.0
                                                + 4374125.0 * nu))
                         * chi_A)
    so_25pn_main_chiS = ((3.0 * e6 * (6693819.0 - 3268968.0 * nu
                                       + 269528.0 * nu2)
                          + 64.0 * (325359.0 - 1496330.0 * nu
                                    + 734356.0 * nu2)
                          + 4.0 * e4 * (8638002.0 + 15159059.0 * nu
                                        + 2643578.0 * nu2)
                          + 24.0 * e2 * (-6113054.0 + 5982331.0 * nu
                                         + 2742362.0 * nu2))
                         * chi_S)
    # sqrt(1-e^2) block
    so_25pn_sqrt_chiA = (delta * (20822976.0 - 69155072.0 * nu
                                  + 3.0 * e6 * (3441339.0
                                                + 769244.0 * nu)
                                  - 24.0 * e2 * (5091614.0
                                                 + 1540063.0 * nu)
                                  + 4.0 * e4 * (4948722.0
                                                + 5603885.0 * nu))
                         * chi_A)
    so_25pn_sqrt_chiS = ((e6 * (10324017.0 + 3203016.0 * nu
                                - 817656.0 * nu2)
                          + 64.0 * (325359.0 - 1496330.0 * nu
                                    + 734356.0 * nu2)
                          + 4.0 * e4 * (4948722.0 + 20078099.0 * nu
                                        + 2028698.0 * nu2)
                          + 24.0 * e2 * (-5091614.0 + 4620411.0 * nu
                                         + 2912602.0 * nu2))
                         * chi_S)
    so_25pn_num = (so_25pn_main_chiA + so_25pn_main_chiS
                   + sqrt_oome2 * (so_25pn_sqrt_chiA + so_25pn_sqrt_chiS))
    so_25pn = (-x**2.5 * so_25pn_num
               / (60480.0 * oome2**5 * (1.0 + sqrt_oome2)))

    # ------------------------------------------------------------------
    # 2PN SS: x^2 * (...) / (120*(1-e^2)^(9/2))
    # ------------------------------------------------------------------
    ss_2pn_num = (
        -8.0 * (1684.0 + 1814.0 * e2 + 143.0 * e4)
        * kappa_S * (-1.0 + 2.0 * nu)
        + (10760.0 - 41600.0 * nu) * chiA2
        + (-3524.0 + 16256.0 * nu) * e2 * chiA2
        + (-963.0 + 4032.0 * nu) * e4 * chiA2
        + 10760.0 * chiS2 - 3524.0 * e2 * chiS2 - 963.0 * e4 * chiS2
        - 1440.0 * nu * chiS2 - 2160.0 * e2 * nu * chiS2
        - 180.0 * e4 * nu * chiS2
        + 2.0 * delta * ((6736.0 + 7256.0 * e2 + 572.0 * e4) * kappa_A
                         + (10760.0 - 3524.0 * e2
                            - 963.0 * e4) * chiAS)
    )
    ss_2pn = x**2 * ss_2pn_num / (120.0 * oome2**4.5)

    # ------------------------------------------------------------------
    # 3PN SS: x^3 * (...) / (60480*(1-e^2)^(11/2)*(1+sqrt(1-e^2)))
    # ------------------------------------------------------------------
    # Main block (no sqrt(1-e^2) factor)
    ss_3pn_kS = (6.0 * kappa_S * (
        32.0 * (88517.0 - 510122.0 * nu + 426748.0 * nu2)
        + e6 * (271948.0 - 1148409.0 * nu + 873600.0 * nu2)
        + 32.0 * e2 * (-521600.0 + 384675.0 * nu + 947247.0 * nu2)
        + 4.0 * e4 * (-2157205.0 + 2335342.0 * nu + 2790004.0 * nu2)))
    ss_3pn_chiA2 = (
        (66222752.0 - 308345888.0 * nu + 140646912.0 * nu2) * chiA2
        + (-145696288.0 + 547646608.0 * nu
           + 92195712.0 * nu2) * e2 * chiA2
        + (37583076.0 - 166049796.0 * nu
           + 20322624.0 * nu2) * e4 * chiA2
        + (19192791.0 - 80303280.0 * nu
           + 9886464.0 * nu2) * e6 * chiA2)
    ss_3pn_chiS2 = (
        (66222752.0 - 211608992.0 * nu + 64464512.0 * nu2) * chiS2
        + (-145696288.0 - 69963824.0 * nu
           + 50171072.0 * nu2) * e2 * chiS2
        + (37583076.0 - 36670452.0 * nu
           + 17593296.0 * nu2) * e4 * chiS2
        + (19192791.0 - 20490792.0 * nu
           + 4780608.0 * nu2) * e6 * chiS2)
    ss_3pn_delta = (-2.0 * delta * (
        3.0 * kappa_A * (
            800.0 * e2 * (20864.0 + 26341.0 * nu)
            + 32.0 * (-88517.0 + 333088.0 * nu)
            + e6 * (-271948.0 + 604513.0 * nu)
            + e4 * (8628820.0 + 7916272.0 * nu))
        + (12.0 * e4 * (-3131923.0 + 2182831.0 * nu)
           + 16.0 * e2 * (9106018.0 + 3284449.0 * nu)
           + 32.0 * (-2069461.0 + 3985373.0 * nu)
           + 3.0 * e6 * (-6397597.0 + 4003818.0 * nu)) * chiAS))
    # sqrt(1-e^2) block
    ss_3pn_sqrt_kS = (6.0 * kappa_S * (
        3.0 * e6 * (-225564.0 + 362557.0 * nu + 155680.0 * nu2)
        + 96.0 * e2 * (-149040.0 + 69705.0 * nu + 326389.0 * nu2)
        + 32.0 * (88517.0 - 510122.0 * nu + 426748.0 * nu2)
        + 4.0 * e4 * (-2515885.0 + 3180802.0 * nu
                       + 2636284.0 * nu2)))
    ss_3pn_sqrt_chiA2 = (
        (66222752.0 - 308345888.0 * nu + 140646912.0 * nu2) * chiA2
        + (-123224608.0 + 453674128.0 * nu
           + 104452992.0 * nu2) * e2 * chiA2
        + (24055716.0 - 109480836.0 * nu
           + 12944064.0 * nu2) * e4 * chiA2
        + (10248471.0 - 42899760.0 * nu
           + 5007744.0 * nu2) * e6 * chiA2)
    ss_3pn_sqrt_chiS2 = (
        (66222752.0 - 211608992.0 * nu + 64464512.0 * nu2) * chiS2
        + (-123224608.0 - 102649904.0 * nu
           + 58342592.0 * nu2) * e2 * chiS2
        + (24055716.0 - 16994292.0 * nu
           + 12674256.0 * nu2) * e4 * chiS2
        + (10248471.0 - 7480872.0 * nu
           + 1528128.0 * nu2) * e6 * chiS2)
    ss_3pn_sqrt_delta = (-2.0 * delta * (
        3.0 * kappa_A * (
            4320.0 * e2 * (3312.0 + 5075.0 * nu)
            + 3.0 * e6 * (225564.0 + 88571.0 * nu)
            + 32.0 * (-88517.0 + 333088.0 * nu)
            + 4.0 * e4 * (2515885.0 + 1850968.0 * nu))
        + (9.0 * e6 * (-1138719.0 + 521486.0 * nu)
           + 12.0 * e4 * (-2004643.0 + 1260511.0 * nu)
           + 32.0 * (-2069461.0 + 3985373.0 * nu)
           + 16.0 * e2 * (7701538.0 + 4433569.0 * nu)) * chiAS))

    ss_3pn_main = ss_3pn_kS + ss_3pn_chiA2 + ss_3pn_chiS2 + ss_3pn_delta
    ss_3pn_sqrt = sqrt_oome2 * (ss_3pn_sqrt_kS + ss_3pn_sqrt_chiA2
                                + ss_3pn_sqrt_chiS2 + ss_3pn_sqrt_delta)
    ss_3pn = (x**3 * (ss_3pn_main + ss_3pn_sqrt)
              / (60480.0 * oome2**5.5 * (1.0 + sqrt_oome2)))

    # ------------------------------------------------------------------
    # 3PN (non-spin): -x^3 * (...) / (8382528000*(1-e^2)^(11/2)*(1+sqrt(1-e^2)))
    # ------------------------------------------------------------------
    log_x = math.log(x)
    log_arg_inner = (1.0 + sqrt_oome2) * x / (2.0 * oome2)
    log_inner = math.log(log_arg_inner)

    # Eccentricity polynomial for EulerGamma and Log/Pi^2 terms
    eg_poly = (24608.0 + 89024.0 * e2 + 42884.0 * e4 + 1719.0 * e6)

    # Main block (not multiplied by sqrt(1-e^2))
    pn3_main = (
        -41929295427264.0
        - 206465835344064.0 * e2
        - 232352869058856.0 * e4
        - 2485135122851556.0 * e6
        + 11381237848025955.0 * e8
        - 23455473860294784.0 * e10
        + 27071901657218880.0 * e12
        - 18124753551303168.0 * e14
        + 6610593256800192.0 * e16
        - 1020232808622720.0 * e18
        + 7006877982720.0 * EULER_GAMMA
        + 25348679516160.0 * e2 * EULER_GAMMA
        + 12210783298560.0 * e4 * EULER_GAMMA
        + 489467784960.0 * e6 * EULER_GAMMA
        - 2291969433600.0 * PI**2
        - 8291624140800.0 * e2 * PI**2
        - 3994181452800.0 * e4 * PI**2
        - 160106284800.0 * e6 * PI**2
        + 24375719121600.0 * nu
        - 62018474179200.0 * e2 * nu
        + 78553258707000.0 * e4 * nu
        + 47873641384800.0 * e6 * nu
        - 709055424000.0 * e8 * nu
        - 834387523200.0 * PI**2 * nu
        + 1504570636800.0 * e2 * PI**2 * nu
        + 1149967872900.0 * e4 * PI**2 * nu
        + 13186473300.0 * e6 * PI**2 * nu
        + 1983096561600.0 * nu2
        + 50052530959200.0 * e2 * nu2
        + 62213110759800.0 * e4 * nu2
        + 5953045190400.0 * e6 * nu2
        - 514084032000.0 * e8 * nu2
        + 798806624000.0 * nu3
        + 5965749020000.0 * e2 * nu3
        + 7164771768000.0 * e4 * nu3
        + 1570602880000.0 * e6 * nu3
        + 31322368000.0 * e8 * nu3
        + 6569517588480.0 * LOG2
        + 265240855756800.0 * e2 * LOG2
        - 2933100915655680.0 * e4 * LOG2
        + 16427137386401280.0 * e6 * LOG2
        - 47525440358753280.0 * e8 * LOG2
        + 80668041174927360.0 * e10 * LOG2
        - 83816763042862080.0 * e12 * LOG2
        + 52672815704678400.0 * e14 * LOG2
        - 18443948344335360.0 * e16 * LOG2
        + 2769559639418880.0 * e18 * LOG2
        + 7472712360960.0 * LOG3
        - 102749794963200.0 * e2 * LOG3
        + 633429133722000.0 * e4 * LOG3
        - 2262947472933840.0 * e6 * LOG3
        + 5088099789899280.0 * e8 * LOG3
        - 7415382645815760.0 * e10 * LOG3
        + 6995743142295600.0 * e12 * LOG3
        - 4125754551164400.0 * e14 * LOG3
        + 1383736159214640.0 * e16 * LOG3
        - 201646472615280.0 * e18 * LOG3
        + 868957031250000.0 * e4 * LOG5
        - 6662003906250000.0 * e6 * LOG5
        + 21723925781250000.0 * e8 * LOG5
        - 39103066406250000.0 * e10 * LOG5
        + 41999589843750000.0 * e12 * LOG5
        - 26937667968750000.0 * e14 * LOG5
        + 9558527343750000.0 * e16 * LOG5
        - 1448261718750000.0 * e18 * LOG5
        + 427109760.0 * eg_poly * log_x
        - 284739840.0 * eg_poly * log_inner
    )

    # sqrt(1-e^2) block
    pn3_sqrt = sqrt_oome2 * (
        -39965726246592.0
        - 162475748753856.0 * e2
        - 125814738638376.0 * e4
        - 2452794581656836.0 * e6
        + 8240642128868355.0 * e8
        - 12521984476370688.0 * e10
        + 10123719402443328.0 * e12
        - 4252485881407104.0 * e14
        + 733604849486784.0 * e16
        + 7006877982720.0 * EULER_GAMMA
        + 25348679516160.0 * e2 * EULER_GAMMA
        + 12210783298560.0 * e4 * EULER_GAMMA
        + 489467784960.0 * e6 * EULER_GAMMA
        - 2291969433600.0 * PI**2
        - 8291624140800.0 * e2 * PI**2
        - 3994181452800.0 * e4 * PI**2
        - 160106284800.0 * e6 * PI**2
        + 24375719121600.0 * nu
        - 38365525968000.0 * e2 * nu
        + 64875068643000.0 * e4 * nu
        + 36614796372000.0 * e6 * nu
        + 575031441600.0 * e8 * nu
        - 834387523200.0 * PI**2 * nu
        + 1323182044800.0 * e2 * PI**2 * nu
        + 1259159031900.0 * e4 * PI**2 * nu
        + 85383906300.0 * e6 * PI**2 * nu
        + 1983096561600.0 * nu2
        + 44062562728800.0 * e2 * nu2
        + 60944647995000.0 * e4 * nu2
        + 12469436179200.0 * e6 * nu2
        + 227955974400.0 * e8 * nu2
        + 798806624000.0 * nu3
        + 5965749020000.0 * e2 * nu3
        + 7164771768000.0 * e4 * nu3
        + 1570602880000.0 * e6 * nu3
        + 31322368000.0 * e8 * nu3
        + 6569517588480.0 * LOG2
        + 242789688852480.0 * e2 * LOG2
        - 2467945357194240.0 * e4 * LOG2
        + 11338118901204480.0 * e6 * LOG2
        - 25502330828620800.0 * e8 * LOG2
        + 32178907939368960.0 * e10 * LOG2
        - 23334134897525760.0 * e12 * LOG2
        + 9124278604277760.0 * e14 * LOG2
        - 1496141950786560.0 * e16 * LOG2
        + 7472712360960.0 * LOG3
        - 80331657880320.0 * e2 * LOG3
        + 392434160081040.0 * e4 * LOG3
        - 1086112037213280.0 * e6 * LOG3
        + 1832565945394800.0 * e8 * LOG3
        - 1924690477469760.0 * e10 * LOG3
        + 1231012600337520.0 * e12 * LOG3
        - 439722417990240.0 * e14 * LOG3
        + 67371172379280.0 * e16 * LOG3
        + 868957031250000.0 * e4 * LOG5
        - 5213742187500000.0 * e6 * LOG5
        + 13034355468750000.0 * e8 * LOG5
        - 17379140625000000.0 * e10 * LOG5
        + 13034355468750000.0 * e12 * LOG5
        - 5213742187500000.0 * e14 * LOG5
        + 868957031250000.0 * e16 * LOG5
        + 427109760.0 * eg_poly * log_x
        - 284739840.0 * eg_poly * log_inner
    )

    pn3_num = pn3_main + pn3_sqrt
    term_3pn = (-x**3 * pn3_num
                / (8382528000.0 * oome2**5.5 * (1.0 + sqrt_oome2)))

    # ------------------------------------------------------------------
    # Assemble: edot = -(e*x^4*nu) * bracket
    # ------------------------------------------------------------------
    bracket = (term_0pn + tail_15pn + term_1pn + term_2pn
               + tail_25pn + so_15pn + so_25pn_tail
               + so_25pn + ss_2pn + ss_3pn + term_3pn)

    return -e * x**4 * nu * bracket


@njit(cache=True, fastmath=True)
def _xdot_numba(e, x, nu, chi_S, chi_A, delta, kappa_S, kappa_A):
    e2 = e * e
    e4 = e2 * e2
    e6 = e4 * e2
    e8 = e4 * e4
    e10 = e8 * e2
    e12 = e8 * e4
    e14 = e8 * e6
    e16 = e8 * e8
    e18 = e16 * e2
    nu2 = nu * nu
    nu3 = nu2 * nu
    oome2 = 1.0 - e2
    sqrt_oome2 = math.sqrt(oome2)
    sqrt_x = math.sqrt(x)

    chiA2 = chi_A * chi_A
    chiS2 = chi_S * chi_S
    chiAS = chi_A * chi_S

    # Leading prefactor: 2*x^5*nu/3
    prefactor = 2.0 * x**5 * nu / 3.0

    # ------------------------------------------------------------------
    # 0PN
    # ------------------------------------------------------------------
    term_0pn = (96.0 + 292.0 * e2 + 37.0 * e4) / (5.0 * oome2**3.5)

    # ------------------------------------------------------------------
    # 1.5PN tail (non-spin):
    #   (36864 + 448320*e^2 + 2061840*e^4 + 6204647*e^6)*Pi*x^(3/2) / 480
    # NOTE: no (1-e^2) in denominator (unlike resummed)
    # ------------------------------------------------------------------
    tail_15pn = (PI * x**1.5
                 * (36864.0 + 448320.0 * e2 + 2061840.0 * e4
                    + 6204647.0 * e6)
                 / 480.0)

    # ------------------------------------------------------------------
    # 1PN (non-spin): same as resummed
    # ------------------------------------------------------------------
    pn1_num = (16.0 * (743.0 + 924.0 * nu)
               + e6 * (6931.0 + 2072.0 * nu)
               + 14.0 * e4 * (7079.0 + 3690.0 * nu)
               + 8.0 * e2 * (15411.0 + 11158.0 * nu))
    term_1pn = -x * pn1_num / (280.0 * oome2**4.5)

    # ------------------------------------------------------------------
    # 2PN (non-spin): same as resummed
    # ------------------------------------------------------------------
    pn2_num = (6048.0 * sqrt_oome2
               * (-48.0 - 250.0 * e2 + 219.0 * e4 + 79.0 * e6)
               * (-5.0 + 2.0 * nu)
               + 3.0 * e8 * (734703.0 + 290664.0 * nu + 58016.0 * nu2)
               + 32.0 * (-11257.0 + 141093.0 * nu + 59472.0 * nu2)
               + 6.0 * e6 * (5905155.0 + 6204657.0 * nu + 1292312.0 * nu2)
               + 16.0 * e2 * (-2678686.0 + 5601690.0 * nu
                              + 1331295.0 * nu2)
               + 12.0 * e4 * (896914.0 + 11637378.0 * nu
                              + 2585233.0 * nu2))
    term_2pn = x**2 * pn2_num / (30240.0 * oome2**5.5)

    # ------------------------------------------------------------------
    # 2.5PN tail (non-spin):
    #   Pi*x^(5/2) * (168*A + Sqrt[1-e^2]*B)
    #   / (20160*(1-e^2)^(3/2))
    # ------------------------------------------------------------------
    tail25_A = (18432.0 + 120384.0 * e2 + 347760.0 * e4
                + 730751.0 * e6)
    tail25_B = (-576.0 * (9535.0 + 15876.0 * nu)
                - 1152.0 * e2 * (87293.0 + 125242.0 * nu)
                - 9.0 * e4 * (67453229.0 + 84958988.0 * nu)
                - e6 * (2152537381.0 + 2501698272.0 * nu)
                + e8 * (3600810502.0 + 3419752524.0 * nu))
    tail_25pn = (PI * x**2.5
                 * (168.0 * tail25_A + sqrt_oome2 * tail25_B)
                 / (20160.0 * oome2**1.5))

    # ------------------------------------------------------------------
    # 1.5PN SO: x^(3/2) * (...) / (30*(1-e^2)^5)
    #   Same as resummed
    # ------------------------------------------------------------------
    so_15pn_chiA = ((-5424.0 - 12536.0 * e2 + 2602.0 * e4
                     + 747.0 * e6) * delta * chi_A)
    so_15pn_chiS = ((-9.0 * e6 * (-83.0 + 8.0 * nu)
                     + 48.0 * (-113.0 + 76.0 * nu)
                     + 8.0 * e2 * (-1567.0 + 1670.0 * nu)
                     + e4 * (2602.0 + 4072.0 * nu)) * chi_S)
    so_15pn = x**1.5 * (so_15pn_chiA + so_15pn_chiS) / (30.0 * oome2**5)

    # ------------------------------------------------------------------
    # 2PN SS: x^2 * (...) / (40*(1-e^2)^(11/2))
    #   Same as resummed
    # ------------------------------------------------------------------
    ss_2pn_num = (
        8.0 * (480.0 + 2064.0 * e2 + 1064.0 * e4 + 33.0 * e6)
        * (delta * kappa_A + kappa_S - 2.0 * kappa_S * nu)
        + (48.0 * (81.0 - 320.0 * nu)
           + 3.0 * e6 * (-199.0 + 832.0 * nu)
           - 8.0 * e2 * (-865.0 + 3232.0 * nu)
           + 2.0 * e4 * (-1969.0 + 8704.0 * nu)) * chiA2
        + 2.0 * (3888.0 + 6920.0 * e2 - 3938.0 * e4
                 - 597.0 * e6) * delta * chiAS
        + (48.0 * (81.0 - 4.0 * nu)
           - 3.0 * e6 * (199.0 + 36.0 * nu)
           - 8.0 * e2 * (-865.0 + 228.0 * nu)
           - 2.0 * e4 * (1969.0 + 828.0 * nu)) * chiS2
    )
    ss_2pn = x**2 * ss_2pn_num / (40.0 * oome2**5.5)

    # ------------------------------------------------------------------
    # 2.5PN SO (non-tail): -x^(5/2) * (...) / (6720*(1-e^2)^6)
    #   Same as resummed
    # ------------------------------------------------------------------
    so_25pn_num = (
        delta * (4008832.0 - 6230784.0 * nu
                 - 224.0 * e4 * (80924.0 + 13833.0 * nu)
                 + 9.0 * e8 * (125467.0 + 27916.0 * nu)
                 - 32.0 * e2 * (642396.0 + 696941.0 * nu)
                 + e6 * (9793328.0 + 4249140.0 * nu)) * chi_A
        + (-9.0 * e8 * (-125467.0 - 41528.0 * nu + 8008.0 * nu2)
           + 128.0 * (31319.0 - 91900.0 * nu + 26544.0 * nu2)
           + 448.0 * e4 * (-40462.0 + 79817.0 * nu + 36774.0 * nu2)
           + 4.0 * e6 * (2448332.0 + 3133943.0 * nu + 337722.0 * nu2)
           + 32.0 * e2 * (-642396.0 - 125759.0 * nu
                          + 632758.0 * nu2)) * chi_S
        + oome2**1.5 * (
            -3584.0 * e2 * (304.0 + 121.0 * e2) * delta
            * (-3.0 + nu) * chi_A
            + 1792.0 * e2 * (304.0 + 121.0 * e2)
            * (6.0 - 8.0 * nu + nu2) * chi_S
        )
    )
    so_25pn = -x**2.5 * so_25pn_num / (6720.0 * oome2**6)

    # ------------------------------------------------------------------
    # 2.5PN SO tail:
    #   Pi*x^3 * (2*A*delta*chiA + 2*(-1+e^2)*B*chiS
    #             + Sqrt[1-e^2]*(-6*C*delta*chiA + D*chiS))
    #   / (720*(1-e^2)^(5/2))
    # ------------------------------------------------------------------
    so_25pn_tail_A = (-73728.0 + 522048.0 * e2 + 6454080.0 * e4
                      + 24159089.0 * e6 - 86903312.0 * e8
                      + 55841823.0 * e10)
    # (-1+e^2) = -(1-e^2) = -oome2
    so_25pn_tail_B = (55841823.0 * e8
                      - 36864.0 * (-2.0 + nu)
                      - 448320.0 * e2 * (1.0 + nu)
                      - 240.0 * e4 * (28760.0 + 8591.0 * nu)
                      - e6 * (31061489.0 + 6204647.0 * nu))
    so_25pn_tail_C = (61824.0 + 1020416.0 * e2 + 5393020.0 * e4
                      + 17001943.0 * e6 - 48416774.0 * e8
                      + 27374225.0 * e10)
    so_25pn_tail_D = (e8 * (290500644.0 - 126600314.0 * nu)
                      + 2304.0 * (-161.0 + 116.0 * nu)
                      + 192.0 * e2 * (-31888.0 + 17303.0 * nu)
                      + 24.0 * e4 * (-1348255.0 + 621086.0 * nu)
                      + e6 * (-102011658.0 + 42863983.0 * nu)
                      + e10 * (-164245350.0 + 72544789.0 * nu))
    so_25pn_tail_num = (2.0 * so_25pn_tail_A * delta * chi_A
                        + 2.0 * (-oome2) * so_25pn_tail_B * chi_S
                        + sqrt_oome2 * (-6.0 * so_25pn_tail_C
                                        * delta * chi_A
                                        + so_25pn_tail_D * chi_S))
    so_25pn_tail = (PI * x**3 * so_25pn_tail_num
                    / (720.0 * oome2**2.5))

    # ------------------------------------------------------------------
    # 3PN SS: -x^3 * (...) / (20160*(1-e^2)^(13/2))
    #   Same as resummed
    # ------------------------------------------------------------------
    # kappa terms
    ss_3pn_kappa = (
        6.0 * delta * kappa_A * (
            192.0 * (-8963.0 + 13706.0 * nu)
            + 3.0 * e8 * (41268.0 + 24115.0 * nu)
            + 96.0 * e2 * (55623.0 + 164080.0 * nu)
            + 4.0 * e6 * (1175865.0 + 952294.0 * nu)
            + 8.0 * e4 * (1721169.0 + 2248456.0 * nu)
        )
        - 6.0 * kappa_S * (
            192.0 * (8963.0 - 31632.0 * nu + 14784.0 * nu2)
            + 3.0 * e8 * (-41268.0 + 58421.0 * nu + 44576.0 * nu2)
            + 96.0 * e2 * (-55623.0 - 52834.0 * nu + 223944.0 * nu2)
            + 8.0 * e4 * (-1721169.0 + 1193882.0 * nu
                          + 3223136.0 * nu2)
            + e6 * (-4703460.0 + 5597744.0 * nu + 5745488.0 * nu2)
        )
    )
    # chiA^2 terms
    ss_3pn_chiA2 = (
        (-576.0 * (55817.0 - 243029.0 * nu + 59136.0 * nu2)
         - 9.0 * e8 * (503031.0 - 2069104.0 * nu + 112000.0 * nu2)
         - 12.0 * e6 * (2460015.0 - 10429817.0 * nu + 589232.0 * nu2)
         - 32.0 * e2 * (-593801.0 + 851591.0 * nu + 4835712.0 * nu2)
         - 8.0 * e4 * (-8736761.0 + 31182647.0 * nu
                       + 8270976.0 * nu2))
        * chiA2
    )
    # delta*chiA*chiS terms
    ss_3pn_chiAS = (
        2.0 * delta * (
            576.0 * (-55817.0 + 68481.0 * nu)
            + 9.0 * e8 * (-503031.0 + 141694.0 * nu)
            + 12.0 * e6 * (-2460015.0 + 897617.0 * nu)
            + 32.0 * e2 * (593801.0 + 3657185.0 * nu)
            + 8.0 * e4 * (8736761.0 + 6220865.0 * nu)
        ) * chiAS
    )
    # chiS^2 terms
    ss_3pn_chiS2 = (
        (-576.0 * (55817.0 - 117201.0 * nu + 33460.0 * nu2)
         - 9.0 * e8 * (503031.0 - 226408.0 * nu + 57792.0 * nu2)
         - 12.0 * e6 * (2460015.0 - 1205477.0 * nu + 797748.0 * nu2)
         - 32.0 * e2 * (-593801.0 - 5790757.0 * nu + 1987972.0 * nu2)
         - 8.0 * e4 * (-8736761.0 - 8677333.0 * nu
                       + 5503540.0 * nu2))
        * chiS2
    )
    # sqrt(1-e^2) block inside 3PN SS
    poly_48 = 48.0 - 358.0 * e2 + 147.0 * e4 + 163.0 * e6
    ss_3pn_sqrt = sqrt_oome2 * (
        -1344.0 * poly_48 * (delta * kappa_A * (-14.0 + 5.0 * nu)
                             + kappa_S * (-14.0 + 33.0 * nu
                                          - 6.0 * nu2))
        + 2688.0 * poly_48 * (11.0 - 46.0 * nu + 6.0 * nu2) * chiA2
        - 5376.0 * poly_48 * delta * (-11.0 + 9.0 * nu) * chiAS
        + 2688.0 * poly_48 * (11.0 - 16.0 * nu + 4.0 * nu2) * chiS2
    )

    ss_3pn_total = (ss_3pn_kappa + ss_3pn_chiA2 + ss_3pn_chiAS
                    + ss_3pn_chiS2 + ss_3pn_sqrt)
    ss_3pn = -x**3 * ss_3pn_total / (20160.0 * oome2**6.5)

    # ------------------------------------------------------------------
    # 3PN (non-spin): -x^3 * (...) / (2794176000*(1-e^2)^(13/2))
    #   Structure: -x^3 * (1584*sqrt(1-e^2)*S + 7*M) / denom
    # ------------------------------------------------------------------
    log_x = math.log(x)
    log_arg_inner = (1.0 + sqrt_oome2) * x / (2.0 * oome2)
    log_inner = math.log(log_arg_inner)

    # Eccentricity polynomial for Log[x] and Log[...] terms
    xlog_poly = (3072.0 + 43520.0 * e2 + 82736.0 * e4
                 + 28016.0 * e6 + 891.0 * e8)

    # 1584*Sqrt[1-e^2] block
    sq_inner = (
        16.0 * (206935598.0
                + 525.0 * (-19748.0 + 861.0 * PI**2) * nu
                - 13935600.0 * nu2)
        + 15.0 * e4 * (245.0 * (-960472.0 + 6027.0 * PI**2) * nu
                       + 55468000.0 * nu2
                       + 4.0 * (845002175.0
                                + 4894313536.0 * LOG2
                                - 2535721524.0 * LOG3))
        - 2.0 * e2 * (175.0 * (-19288240.0 + 154119.0 * PI**2) * nu
                       + 1195874400.0 * nu2
                       + 96.0 * (-172422996.0
                                 + 73821440.0 * LOG2
                                 - 73712835.0 * LOG3))
        + 4.0 * e12 * (-2674902502332.0
                        + 9545869341120.0 * LOG2
                        - 909837522405.0 * LOG3
                        - 4571533203125.0 * LOG5)
        + 30.0 * e8 * (-65985944830.0
                        + 4944380.0 * nu + 3512320.0 * nu2
                        + 463449274624.0 * LOG2
                        - 68508708849.0 * LOG3
                        - 182861328125.0 * LOG5)
        + 42.0 * e16 * (-88338570336.0
                         + 254746969600.0 * LOG2
                         - 19786630995.0 * LOG3
                         - 130615234375.0 * LOG5)
        - 35.0 * e18 * (-18402467688.0
                         + 49955981952.0 * LOG2
                         - 3637201887.0 * LOG3
                         - 26123046875.0 * LOG5)
        + 5.0 * e6 * (5289957464.0
                       + 35.0 * (-18306272.0 + 140343.0 * PI**2) * nu
                       + 335465760.0 * nu2
                       - 642552839040.0 * LOG2
                       + 148590332793.0 * LOG3
                       + 182861328125.0 * LOG5)
        + 3.0 * e14 * (2919248247032.0
                        - 9164254440320.0 * LOG2
                        + 775680162705.0 * LOG3
                        + 4571533203125.0 * LOG5)
        + e10 * (6902455419144.0
                 - 30611826537600.0 * LOG2
                 + 3466346065875.0 * LOG3
                 + 13714599609375.0 * LOG5)
    )
    sqrt_3pn = 1584.0 * sqrt_oome2 * sq_inner

    # 7 * (main block)
    main_3pn = 7.0 * (
        -1651478220672.0
        - 17993851436736.0 * e2
        - 39170644333104.0 * e4
        - 13779478212264.0 * e6
        + 716039891946.0 * e8
        + 77900759775.0 * e10
        + 124960112640.0 * EULER_GAMMA
        + 1770268262400.0 * e2 * EULER_GAMMA
        + 3365462200320.0 * e4 * EULER_GAMMA
        + 1139610193920.0 * e6 * EULER_GAMMA
        + 36243313920.0 * e8 * EULER_GAMMA
        - 40874803200.0 * PI**2
        - 579059712000.0 * e2 * PI**2
        - 1100852121600.0 * e4 * PI**2
        - 372769689600.0 * e6 * PI**2
        - 11855289600.0 * e8 * PI**2
        + 2015730851200.0 * nu
        - 44311784000.0 * e2 * nu
        + 1321319626000.0 * e4 * nu
        + 7451326891800.0 * e6 * nu
        + 1812964032000.0 * e8 * nu
        + 25126041600.0 * e10 * nu
        - 73646496000.0 * PI**2 * nu
        - 80806572000.0 * e2 * PI**2 * nu
        + 245846323800.0 * e4 * PI**2 * nu
        + 162917300700.0 * e6 * PI**2 * nu
        + 7594794900.0 * e8 * PI**2 * nu
        + 45827337600.0 * nu2
        + 2909366856000.0 * e2 * nu2
        + 8249097423600.0 * e4 * nu2
        + 5180200759800.0 * e6 * nu2
        + 703615334400.0 * e8 * nu2
        + 10135065600.0 * e10 * nu2
        + 16572864000.0 * nu3
        + 343803152000.0 * e2 * nu3
        + 1044493604000.0 * e4 * nu3
        + 710550456000.0 * e6 * nu3
        + 101871616000.0 * e8 * nu3
        + 1458688000.0 * e10 * nu3
        + 249920225280.0 * LOG2
        + 3540536524800.0 * e2 * LOG2
        + 6730924400640.0 * e4 * LOG2
        + 2279220387840.0 * e6 * LOG2
        + 72486627840.0 * e8 * LOG2
        + 61015680.0 * xlog_poly * log_x
        - 40677120.0 * xlog_poly * log_inner
    )

    pn3_num = sqrt_3pn + main_3pn
    term_3pn = -x**3 * pn3_num / (2794176000.0 * oome2**6.5)

    # ------------------------------------------------------------------
    # Assemble
    # ------------------------------------------------------------------
    bracket = (term_0pn + tail_15pn + so_15pn + term_1pn
               + tail_25pn + so_25pn_tail + term_2pn + ss_2pn
               + so_25pn + ss_3pn + term_3pn)

    return prefactor * bracket


def edot(e, x, nu, chi_S=0.0, chi_A=0.0, delta=None,
         kappa_S=0.0, kappa_A=0.0):
    """Public wrapper for non-resummed de/dt."""
    if delta is None:
        arg = 1.0 - 4.0 * nu
        delta = math.sqrt(max(arg, 0.0))
    return _edot_numba(e, x, nu, chi_S, chi_A, delta, kappa_S, kappa_A)


def xdot(e, x, nu, chi_S=0.0, chi_A=0.0, delta=None,
         kappa_S=0.0, kappa_A=0.0):
    """Public wrapper for non-resummed dx/dt."""
    if delta is None:
        arg = 1.0 - 4.0 * nu
        delta = math.sqrt(max(arg, 0.0))
    return _xdot_numba(e, x, nu, chi_S, chi_A, delta, kappa_S, kappa_A)


@njit(cache=True, fastmath=True)
def rhs_inner(e_val, x_val, zeta_val, nu, chi_S, chi_A,
              delta, kappa_S, kappa_A):
    """Pure numba RHS returning (de, dx, dz) as a tuple."""
    if e_val < 0.0 or x_val <= 0.0 or x_val > 1.0 or e_val >= 1.0:
        return (0.0, 0.0, 0.0)
    de = _edot_numba(e_val, x_val, nu, chi_S, chi_A, delta,
                     kappa_S, kappa_A)
    dx = _xdot_numba(e_val, x_val, nu, chi_S, chi_A, delta,
                     kappa_S, kappa_A)
    dz = _zetadot_numba(e_val, x_val, zeta_val, nu, chi_S, chi_A,
                        delta, kappa_S, kappa_A)
    return (de, dx, dz)


def _rhs(t, y, nu, chi_S, chi_A, delta, kappa_S, kappa_A):
    """ODE RHS compatible with solve_ivp."""
    de, dx, dz = rhs_inner(y[0], y[1], y[2], nu, chi_S, chi_A,
                           delta, kappa_S, kappa_A)
    return [de, dx, dz]


def integrate_eob_eccentric_dynamics(q, chi1=0.0, chi2=0.0, e0=0.1,
                                     zeta0=0.0, t_eval=None,
                                     omega0=0.0085, t_end=None,
                                     rtol=1e-10, atol=1e-12,
                                     kappa1=1.0, kappa2=1.0,
                                     x_stop=None):
    """Integrate eccentric dynamics using non-resummed 3PN fluxes (numba)."""
    return integrate_dynamics(
        _rhs, rhs_inner, q, chi1, chi2, e0, zeta0, t_eval,
        omega0, t_end, rtol, atol, kappa1, kappa2, x_stop)


